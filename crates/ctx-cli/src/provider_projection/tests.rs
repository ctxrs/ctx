fn line(value: serde_json::Value) -> String {
    format!("{value}\n")
}

fn codex_session(session_id: &str, turns: usize) -> String {
    let mut text = line(json!({
        "timestamp": "2026-07-27T00:00:00Z",
        "type": "session_meta",
        "payload": {
            "id": session_id,
            "timestamp": "2026-07-27T00:00:00Z",
            "cwd": "/workspace",
            "source": "cli"
        }
    }));
    for turn in 0..turns {
        text.push_str(&line(json!({
            "timestamp": "2026-07-27T00:00:01Z",
            "type": "response_item",
            "payload": {
                "type": "message",
                "role": "user",
                "content": [{
                    "type": "input_text",
                    "text": format!("provider projection turn {turn} in {session_id}")
                }]
            }
        })));
    }
    text
}

fn corpus(root: &Path) -> PathBuf {
    let sessions = root.join("sessions");
    fs::create_dir_all(&sessions).unwrap();
    for (index, session_id) in [
        "019f5a54-67de-7422-9841-e9872df75f44",
        "019f5a54-67de-7422-9841-e9872df75f45",
    ]
    .into_iter()
    .enumerate()
    {
        fs::write(
            sessions.join(format!(
                "rollout-2026-07-27T00-00-0{index}-{session_id}.jsonl"
            )),
            codex_session(session_id, 4 + index),
        )
        .unwrap();
    }
    sessions
}

