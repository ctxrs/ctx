#[test]
fn insufficient_disk_refuses_the_rebuild_and_leaves_the_index_installed() {
    let temp = tempdir().unwrap();
    let (data_root, _) = superseded_store(temp.path());
    let db_path = database_path(data_root.clone());
    let before = canonical_counts(&db_path);

    let error = disk::with_available_space(4096, || rebuild(&data_root)).unwrap_err();

    let message = format!("{error}");
    assert!(message.contains("not enough free disk space"), "{message}");
    assert!(message.contains("required"), "{message}");
    assert!(message.contains("available"), "{message}");
    assert_eq!(
        canonical_counts(&db_path),
        before,
        "a refused rebuild must not change a single canonical row"
    );
    assert!(!staging_root(&data_root).exists());
    assert!(!retired_store_path(&db_path).exists());
    assert_eq!(observe(&data_root), ProjectionState::RebuildRequired);

    // With headroom back, the same store rebuilds.
    assert!(matches!(
        rebuild(&data_root).unwrap(),
        RebuildOutcome::Rebuilt(_)
    ));
}

#[test]
fn insufficient_disk_message_names_required_and_available_space() {
    let temp = tempdir().unwrap();
    let db_path = temp.path().join("work.sqlite");
    fs::write(&db_path, vec![0_u8; 4096]).unwrap();
    let headroom = disk::Headroom {
        installed_bytes: 42 * 1024 * 1024 * 1024,
        required_bytes: disk::required_bytes(42 * 1024 * 1024 * 1024),
        available_bytes: 3 * 1024 * 1024 * 1024,
    };

    assert!(!headroom.is_sufficient());
    let message = format!("{}", disk::insufficient_disk_error(&db_path, headroom));
    assert!(message.contains("52.5 GiB"), "{message}");
    assert!(message.contains("3.0 GiB"), "{message}");
    assert!(message.contains("current index is untouched"), "{message}");
    assert_eq!(fs::read(&db_path).unwrap().len(), 4096);
}

#[test]
fn required_headroom_covers_a_second_generation_with_a_floor() {
    // 70 GB of corpus is about 24 GiB of index, and both generations exist at
    // once while the replacement is built.
    let index = 24_u64 * 1024 * 1024 * 1024;
    assert_eq!(disk::required_bytes(index), index / 4 * 5);
    assert_eq!(disk::required_bytes(0), 256 * 1024 * 1024);
    assert!(disk::required_bytes(1024) >= 256 * 1024 * 1024);
}

#[test]
fn recorded_roots_replay_sources_discovery_would_never_find() {
    let temp = tempdir().unwrap();
    let (data_root, sessions) = superseded_store(temp.path());

    let recorded = sources::recorded_roots(&database_path(data_root)).unwrap();

    assert!(
        recorded
            .iter()
            .any(|root| root.provider == CaptureProvider::Codex && root.path == sessions),
        "the store must be able to name the roots it projected: {recorded:?}"
    );
    let replay = sources::replayable_roots(&recorded, &[]);
    assert_eq!(replay.len(), 1);
    assert_eq!(replay[0].path, sessions);

    // A root discovery already covers is not replayed twice.
    let discovered = vec![explicit_path_source(CaptureProvider::Codex, sessions)];
    assert!(sources::replayable_roots(&recorded, &discovered).is_empty());
}
